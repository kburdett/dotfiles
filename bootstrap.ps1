<#
.SYNOPSIS
Set up these dotfiles on Windows. Safe to re-run at any time.

.DESCRIPTION
Points PowerShell 7 and Windows PowerShell 5.1 at the profile in this repo, links the XDG
configs (git, nvim) into place, saves the XDG, DOTFILES and npm config variables for the user,
installs the fonts in fonts\ for the user, and installs the Neovim plugins, parsers and
language servers.
Existing files that would be replaced are moved aside as <name>.bak.<timestamp>.

Needs no admin rights or Developer Mode: folders are linked with directory junctions, the
profiles are one-line files that load the repo's profile, npm finds ~/.npmrc's settings
through NPM_CONFIG_USERCONFIG, and fonts are installed per user (Windows 10 1809 or later).

.PARAMETER Packages
Also install Git, the GitHub CLI, Neovim, Node.js, WinMerge and PowerShell 7 with winget.
#>
[CmdletBinding()]
param(
    [switch]$Packages
)
$ErrorActionPreference = 'Stop'

$DotfilesDir = $PSScriptRoot
. (Join-Path $DotfilesDir 'win\env.ps1')

function Write-Step([string]$Message) {
    Write-Host "`n==> $Message" -ForegroundColor Blue
}

function Resolve-LinkTarget([IO.FileSystemInfo]$Item) {
    # .Target is a string in PowerShell 7 and a string[] in 5.1; it may be relative to the link
    $target = @($Item.Target)[0]
    if (-not $target) { return $null }
    if (-not [IO.Path]::IsPathRooted($target)) {
        $target = Join-Path (Split-Path -Parent $Item.FullName) $target
    }
    [IO.Path]::GetFullPath($target).TrimEnd('\')
}

# Clear $Path for something new: a link is deleted (Delete() removes only the link, never the
# target's contents), a real file or folder is moved aside
function Clear-Path([IO.FileSystemInfo]$Item) {
    if (-not $Item) { return }
    if ($Item.LinkType) {
        $Item.Delete()
    } else {
        $backup = "$($Item.FullName).bak.$(Get-Date -Format yyyyMMddHHmmss)"
        Move-Item -LiteralPath $Item.FullName -Destination $backup
        Write-Host "  backup  $($Item.FullName) -> $backup"
    }
}

# Point the folder $Path at $Target with a directory junction, leaving it alone if it already
# points there (a junction, or a symlink made by older bootstraps)
function Set-Junction([string]$Target, [string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($item -and $item.LinkType -and
        (Resolve-LinkTarget $item) -eq [IO.Path]::GetFullPath($Target).TrimEnd('\')) {
        Write-Host "  ok      $Path"
        return
    }
    Clear-Path $item
    New-Item -ItemType Junction -Path $Path -Target $Target | Out-Null
    Write-Host "  linked  $Path -> $Target"
}

# Write $Content to $Path, leaving it alone if it's already there
function Set-FileContent([string]$Path, [string]$Content) {
    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($item -and -not $item.LinkType -and [IO.File]::ReadAllText($Path) -eq $Content) {
        Write-Host "  ok      $Path"
        return
    }
    Clear-Path $item
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path $parent)) { New-Item -ItemType Directory -Path $parent | Out-Null }
    [IO.File]::WriteAllText($Path, $Content)
    Write-Host "  wrote   $Path"
}

# Save a user environment variable for all new processes (skipped when unchanged: saving is slow)
function Set-UserEnv([string]$Name, [string]$Value) {
    if ([Environment]::GetEnvironmentVariable($Name, 'User') -eq $Value) {
        Write-Host "  ok      $Name"
        return
    }
    [Environment]::SetEnvironmentVariable($Name, $Value, 'User')
    Write-Host "  set     $Name = $Value"
}

if ($Packages) {
    Write-Step 'Installing packages with winget'
    $ids = 'Git.Git', 'GitHub.cli', 'Neovim.Neovim', 'OpenJS.NodeJS.LTS', 'WinMerge.WinMerge', 'Microsoft.PowerShell'
    foreach ($id in $ids) {
        winget list --exact --id $id --accept-source-agreements *> $null
        if ($LASTEXITCODE -eq 0) {
            Write-Host "  ok      $id"
        } else {
            winget install --exact --id $id --silent --accept-package-agreements --accept-source-agreements
        }
    }
    # pick up the new commands in this session
    $Env:PATH = [Environment]::GetEnvironmentVariable('PATH', 'Machine') + ';' + [Environment]::GetEnvironmentVariable('PATH', 'User')
}

Write-Step 'Setting up the PowerShell profiles'
# each edition's profile just loads the one in the repo (replaces symlinks from older bootstraps)
$documents = [Environment]::GetFolderPath('MyDocuments')
$profileSource = (Join-Path $DotfilesDir 'win\profile.ps1') -replace "'", "''"
$profileStub = "# Generated by bootstrap.ps1: load the profile from the dotfiles repo`n. '$profileSource'`n"
foreach ($edition in 'PowerShell', 'WindowsPowerShell') {
    Set-FileContent -Path (Join-Path $documents "$edition\profile.ps1") -Content $profileStub
}

Write-Step "Linking configs into $Env:XDG_CONFIG_HOME"
foreach ($child in Get-ChildItem -LiteralPath (Join-Path $DotfilesDir 'xdg') -Directory) {
    Set-Junction -Target $child.FullName -Path (Join-Path $Env:XDG_CONFIG_HOME $child.Name)
}

Write-Step 'Saving environment variables for the user'
foreach ($name in 'DOTFILES', 'XDG_CONFIG_HOME', 'XDG_DATA_HOME', 'XDG_STATE_HOME', 'XDG_CACHE_HOME', 'NPM_CONFIG_USERCONFIG') {
    Set-UserEnv $name ([Environment]::GetEnvironmentVariable($name))
}

Write-Step 'Installing fonts'
# Per-user install: copied into the user's font folder (Windows only loads fonts from there or
# the system one) and registered under HKCU, so no admin rights are needed
$fontDir = Join-Path $Env:LOCALAPPDATA 'Microsoft\Windows\Fonts'
$fontKey = 'HKCU:\Software\Microsoft\Windows NT\CurrentVersion\Fonts'
if (-not (Test-Path $fontDir)) { New-Item -ItemType Directory -Path $fontDir | Out-Null }
if (-not (Test-Path $fontKey)) { New-Item -Path $fontKey -Force | Out-Null }
if (-not ('Dotfiles.Fonts' -as [type])) {
    Add-Type -Namespace Dotfiles -Name Fonts -MemberDefinition @'
[DllImport("gdi32.dll", CharSet = CharSet.Unicode)]
public static extern int AddFontResource(string path);
[DllImport("user32.dll", CharSet = CharSet.Unicode)]
public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint msg, UIntPtr wParam, IntPtr lParam,
    uint flags, uint timeout, out UIntPtr result);
'@
}
$fontsChanged = $false
$fonts = Get-ChildItem -LiteralPath (Join-Path $DotfilesDir 'fonts') -File -ErrorAction SilentlyContinue |
    Where-Object { $_.Extension -in '.otf', '.ttf' }
foreach ($font in $fonts) {
    $dest = Join-Path $fontDir $font.Name
    $kind = if ($font.Extension -eq '.otf') { 'OpenType' } else { 'TrueType' }
    $valueName = "$($font.BaseName) ($kind)"
    $registered = (Get-ItemProperty -LiteralPath $fontKey -Name $valueName -ErrorAction SilentlyContinue).$valueName
    $current = (Test-Path -LiteralPath $dest) -and
        (Get-FileHash -LiteralPath $dest).Hash -eq (Get-FileHash -LiteralPath $font.FullName).Hash
    if ($current -and $registered -eq $dest) {
        Write-Host "  ok      $($font.Name)"
        continue
    }
    if (-not $current) {
        try {
            Copy-Item -LiteralPath $font.FullName -Destination $dest -Force
        } catch {
            # an updated font can't replace one an open app has loaded
            Write-Host "  skipped $($font.Name): in use, close the apps using it and re-run" -ForegroundColor Yellow
            continue
        }
    }
    Set-ItemProperty -LiteralPath $fontKey -Name $valueName -Value $dest
    [void][Dotfiles.Fonts]::AddFontResource($dest)   # usable now, without signing out
    $fontsChanged = $true
    Write-Host "  copied  $dest"
}
if ($fontsChanged) {
    # tell running apps (WM_FONTCHANGE to HWND_BROADCAST, giving up on hung windows)
    $result = [UIntPtr]::Zero
    [void][Dotfiles.Fonts]::SendMessageTimeout([IntPtr]0xffff, 0x1D, [UIntPtr]::Zero, [IntPtr]::Zero, 2, 1000, [ref]$result)
}

Write-Step 'Configuring Git'
# config.os pulls in the settings for this OS
Set-FileContent -Path (Join-Path $DotfilesDir 'xdg\git\config.os') `
    -Content "# Generated by bootstrap.ps1`n[include]`n`tpath = config.win`n"

git config --global http.sslBackend schannel
$globalCAInfo = git config --global --get-all http.sslCAInfo 2>$null
if ($LASTEXITCODE -eq 0) {
    git config --global --unset-all http.sslCAInfo
}

$localConfig = Join-Path $DotfilesDir 'xdg\git\config.local'
if (Test-Path $localConfig) {
    Write-Host "  ok      $localConfig"
} elseif ([Environment]::UserInteractive -and -not [Console]::IsInputRedirected) {
    $name = Read-Host '  Git user.name'
    $email = Read-Host '  Git user.email'
    [IO.File]::WriteAllText($localConfig, "[user]`n`tname = $name`n`temail = $email`n")
    Write-Host "  wrote   $localConfig"
} else {
    Write-Host "  Create $localConfig with your [user] name and email (see config.local.example)"
}

Write-Step 'Setting the profile'
# Neovim loads plugins only when this file says "full" (see xdg\nvim\init.lua). Written the
# first time; an existing file is left alone.
$profileFile = Join-Path $Env:XDG_CONFIG_HOME 'dotfiles\profile'
if ((Test-Path $profileFile) -and (Get-Item $profileFile).Length -gt 0) {
    Write-Host "  ok      $profileFile"
} else {
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $profileFile) | Out-Null
    [IO.File]::WriteAllText($profileFile, "full`n")
    Write-Host "  wrote   $profileFile"
}
$dotfilesProfile = ([IO.File]::ReadAllText($profileFile)).Trim()
Write-Host "  profile $dotfilesProfile"

if ($dotfilesProfile -ne 'full') {
    Write-Step "Skipping Neovim plugins, parsers and language servers ($dotfilesProfile profile)"
} elseif (Get-Command nvim -ErrorAction SilentlyContinue) {
    Write-Step 'Installing Neovim plugins, parsers and language servers'
    nvim --headless "+lua require('install')" +qa
}

Write-Step 'Done'
if (Get-Command gh -ErrorAction SilentlyContinue) {
    gh auth status *> $null
    if ($LASTEXITCODE -ne 0) { Write-Host 'Sign in to GitHub: gh auth login' }
}
if ($fontsChanged) { Write-Host 'Restart Windows Terminal to pick up the new fonts.' }
Write-Host 'Open a new terminal to load the profile.'
